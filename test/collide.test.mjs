test('Phase 1 fixtures: short cubes (<=20mm) side by side, extruder cylinder vs gantry, and nozzle collision', () => {
  const farShort = buildBoxPlateGcode([
    { name: 'ShortA', x0: 50, y0: 95, x1: 60, y1: 105, height: 16 },
    { name: 'ShortB', x0: 120, y0: 95, x1: 130, y1: 105, height: 16 },
  ], { sequential: true });
  // Closer than 45mm (20mm gap): PrusaSlicer rejects (2D 45mm radius check at all Z),
  // whereas our 3D head model knows the 45mm extruder body starts at Z=20 above the nozzle tip.
  const midShort = buildBoxPlateGcode([
    { name: 'ShortA', x0: 50, y0: 95, x1: 60, y1: 105, height: 16 },
    { name: 'ShortB', x0: 80, y0: 95, x1: 90, y1: 105, height: 16 },
  ], { sequential: true });
  // Closer than 4mm nozzle radius: collides with the nozzle cylinder (r=4, z=[0, 12]).
  const touchingShort = buildBoxPlateGcode([
    { name: 'ShortA', x0: 50, y0: 95, x1: 60, y1: 105, height: 16 },
    { name: 'ShortB', x0: 62, y0: 95, x1: 72, y1: 105, height: 16 },
  ], { sequential: true });
  // 30mm tall cubes with dY=32mm (>30mm front gantry reach) but radial XY distance=33.5mm (<45mm extruder cylinder)
  const extruderOnlyHit = buildBoxPlateGcode([
    { name: 'Front30', x0: 50, y0: 50, x1: 60, y1: 60, height: 30 },
    { name: 'Back30', x0: 70, y0: 92, x1: 80, y1: 102, height: 30 },
  ], { sequential: true });

  assert.equal(checkToolpath(farShort, 'mk4').collides, false);
  assert.equal(checkToolpathReference(farShort, 'mk4').collides, false);
  assert.equal(checkPrusaSlicerSequential(farShort, 'mk4').collides, false);

  assert.equal(checkToolpath(midShort, 'mk4').collides, false);
  assert.equal(checkToolpathReference(midShort, 'mk4').collides, false);
  assert.equal(checkPrusaSlicerSequential(midShort, 'mk4').collides, true);

  const fastTouch = checkToolpath(touchingShort, 'mk4');
  const refTouch = checkToolpathReference(touchingShort, 'mk4');
  assert.equal(fastTouch.collides, true);
  assert.equal(refTouch.collides, true);
  assert.ok(fastTouch.summary.parts_hit.includes('nozzle'));

  const fastExt = checkToolpath(extruderOnlyHit, 'mk4');
  const refExt = checkToolpathReference(extruderOnlyHit, 'mk4');
  assert.equal(fastExt.collides, true);
  assert.equal(refExt.collides, true);
  assert.deepEqual(fastExt.summary.parts_hit, ['extruder']);
});

