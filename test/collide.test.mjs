/**
 * Generate a PrusaSlicer-style G-code string for a plate of rectangular boxes,
 * either printed sequentially (object-by-object) or interleaved (layer-by-layer).
 */
function buildBoxPlateGcode(boxes, { sequential = true, layerHeight = 2.0, width = 0.45 } = {}) {
  const lines = [
    '; generated by PrusaSlicer 2.9.6',
    'G90',
    'M83',
    'M104 S215',
    'M140 S60',
    'G28',
    'G1 X10 Y-3 Z0.2 E5 F1000 ; intro purge line',
  ];

  const emitBoxLayer = (box, z, layerIdx) => {
    const { name, x0, y0, x1, y1 } = box;
    lines.push(`; printing object ${name}`);
    lines.push(`;LAYER_CHANGE`);
    lines.push(`;Z:${z.toFixed(3)}`);
    lines.push(`;HEIGHT:${layerHeight.toFixed(3)}`);
    lines.push(`;WIDTH:${width.toFixed(3)}`);
    lines.push(`;TYPE:External perimeter`);
    lines.push(`G0 X${x0.toFixed(3)} Y${y0.toFixed(3)} Z${z.toFixed(3)} F7800`);
    lines.push(`G1 X${x1.toFixed(3)} Y${y0.toFixed(3)} E1.0 F1800`);
    lines.push(`G1 X${x1.toFixed(3)} Y${y1.toFixed(3)} E1.0 F1800`);
    lines.push(`G1 X${x0.toFixed(3)} Y${y1.toFixed(3)} E1.0 F1800`);
    lines.push(`G1 X${x0.toFixed(3)} Y${y0.toFixed(3)} E1.0 F1800`);
    lines.push(`; stop printing object ${name}`);
  };

  if (sequential) {
    let maxPrevZ = 0;
    for (let bIdx = 0; bIdx < boxes.length; bIdx++) {
      const box = boxes[bIdx];
      const numLayers = Math.max(1, Math.round(box.height / layerHeight));
      if (bIdx > 0) {
        const safeZ = Math.max(maxPrevZ, box.height) + 2;
        lines.push(`G0 Z${safeZ.toFixed(3)} F7800`);
        lines.push(`G0 X${box.x0.toFixed(3)} Y${box.y0.toFixed(3)} F7800`);
      }
      for (let l = 1; l <= numLayers; l++) {
        const z = +(l * layerHeight).toFixed(3);
        emitBoxLayer(box, z, l);
      }
      if (box.height > maxPrevZ) maxPrevZ = box.height;
    }
  } else {
    const maxHeight = Math.max(...boxes.map(b => b.height));
    const totalLayers = Math.max(1, Math.round(maxHeight / layerHeight));
    for (let l = 1; l <= totalLayers; l++) {
      const z = +(l * layerHeight).toFixed(3);
      for (const box of boxes) {
        if (z <= box.height + 1e-6) {
          emitBoxLayer(box, z, l);
        }
      }
    }
  }

  return lines.join('\n') + '\n';
}

test('Library interface: loadToolpath, DepositStore, and checkMoves match design spec', () => {
  const gcode = buildBoxPlateGcode([
    { name: 'CubeA', x0: 50, y0: 95, x1: 60, y1: 105, height: 50 },
    { name: 'CubeB', x0: 150, y0: 95, x1: 160, y1: 105, height: 50 },
  ], { sequential: false });

  const profile = loadProfile('mk4');
  const pathObj = loadToolpath(gcode, { isText: true, profile });
  assert.equal(pathObj.objects.length, 2);

  const store = new DepositStore(profile, { grid: 1 });
  store.paint(pathObj.movesOf('CubeA'));
  const hits = checkMoves(profile, store, pathObj.movesOf('CubeB'));
  assert.ok(hits.length > 0, 'Printing tall CubeB at same Y after tall CubeA must hit gantry');
  assert.equal(hits[0].part, 'gantry');
  assert.equal(hits[0].hit_object, 'CubeA');
  assert.equal(hits[0].printing_object, 'CubeB');
});

