// Deterministic PRNG (Mulberry32) for reproducible property tests
function makeRng(seed = 0x12345678) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

test('Phase 1 Property 1: Any toolpath where the nozzle never drops below the deposited top never collides', () => {
  const rng = makeRng(1001);
  const profile = loadProfile('mk4');

  for (let trial = 0; trial < 25; trial++) {
    const lines = ['G90', 'M83', ';LAYER_CHANGE', ';Z:0.2', ';HEIGHT:0.2', ';WIDTH:0.45'];
    let x = 20 + rng() * 180;
    let y = 20 + rng() * 150;
    let z = 0.2;
    lines.push(`G0 X${x.toFixed(3)} Y${y.toFixed(3)} Z${z.toFixed(3)} F7800`);
    for (let step = 0; step < 40; step++) {
      x = 20 + rng() * 180;
      y = 20 + rng() * 150;
      // Nozzle Z is monotonically non-decreasing -> never drops below deposited top
      z = +(z + rng() * 1.5).toFixed(3);
      const extrude = rng() > 0.3;
      lines.push(`G1 X${x.toFixed(3)} Y${y.toFixed(3)} Z${z.toFixed(3)}${extrude ? ' E1.0' : ''} F1800`);
    }
    const gcode = lines.join('\n') + '\n';
    const fast = checkToolpath(gcode, profile, { isText: true, grid: 1.0, margin: 0.5 });
    const ref = checkToolpathReference(gcode, profile, { isText: true, grid: 1.0, margin: 0.5 });
    assert.equal(fast.collides, false, `Trial ${trial} should never collide when Z is monotonically non-decreasing`);
    assert.equal(ref.collides, false);
  }
});

test('Phase 1 Property 2: Adding deposited material never removes a collision', () => {
  const rng = makeRng(2002);
  const profile = loadProfile('mk4');

  for (let trial = 0; trial < 30; trial++) {
    const storeBase = new DepositStore(profile, { grid: 2.0, margin: 0.5 });
    const storeMore = new DepositStore(profile, { grid: 2.0, margin: 0.5 });

    const baseMoves = [];
    for (let i = 0; i < 15; i++) {
      const x0 = 40 + rng() * 150;
      const y0 = 40 + rng() * 120;
      const x1 = x0 + (rng() - 0.5) * 30;
      const y1 = y0 + (rng() - 0.5) * 30;
      const z = 5 + rng() * 45;
      baseMoves.push({
        line: i + 1, kind: 'G1',
        x0, y0, z0: z, x1, y1, z1: z,
        extruding: true, dE: 1, width: 0.45, height: 0.2, object: 'BaseObj',
      });
    }

    const extraMoves = [];
    for (let i = 0; i < 15; i++) {
      const x0 = 40 + rng() * 150;
      const y0 = 40 + rng() * 120;
      const x1 = x0 + (rng() - 0.5) * 30;
      const y1 = y0 + (rng() - 0.5) * 30;
      const z = 5 + rng() * 55;
      extraMoves.push({
        line: i + 100, kind: 'G1',
        x0, y0, z0: z, x1, y1, z1: z,
        extruding: true, dE: 1, width: 0.45, height: 0.2, object: 'ExtraObj',
      });
    }

    storeBase.paint(baseMoves);
    storeMore.paint(baseMoves);
    storeMore.paint(extraMoves);

    const probeMoves = [];
    for (let i = 0; i < 10; i++) {
      const x0 = 40 + rng() * 150;
      const y0 = 40 + rng() * 120;
      const x1 = 40 + rng() * 150;
      const y1 = 40 + rng() * 120;
      const z0 = 1 + rng() * 35;
      const z1 = 1 + rng() * 35;
      probeMoves.push({
        line: i + 200, kind: 'G0',
        x0, y0, z0, x1, y1, z1,
        extruding: false, dE: 0, width: 0.45, height: 0.2, object: 'Probe',
      });
    }

    const hitsBase = checkMoves(profile, storeBase, probeMoves);
    const hitsMore = checkMoves(profile, storeMore, probeMoves);

    // Every (line, part) collision present in hitsBase must also be present in hitsMore with >= penetration
    for (const hb of hitsBase) {
      const hm = hitsMore.find(h => h.line === hb.line && h.part === hb.part);
      assert.ok(hm, `Collision at line ${hb.line} (${hb.part}) disappeared after adding deposited material`);
      assert.ok(hm.penetration_mm + 1e-6 >= hb.penetration_mm);
    }
  }
});

test('Phase 1 Property 3: Halving the grid or shrinking the margin never adds a collision; fast matches reference', () => {
  const rng = makeRng(3003);
  const profile = loadProfile('mk4');

  for (let trial = 0; trial < 25; trial++) {
    const storeCoarse = new DepositStore(profile, { grid: 2.0, margin: 1.0 });
    const storeFineGrid = new DepositStore(profile, { grid: 1.0, margin: 1.0 });
    const storeSmallMargin = new DepositStore(profile, { grid: 2.0, margin: 0.5 });
    const refCoarse = new ReferenceVoxelStore(profile, { grid: 2.0, margin: 1.0 });

    const depMoves = [];
    for (let i = 0; i < 12; i++) {
      const x0 = 50 + rng() * 120;
      const y0 = 50 + rng() * 100;
      const x1 = x0 + (rng() - 0.5) * 20;
      const y1 = y0 + (rng() - 0.5) * 20;
      const z0 = 2 + rng() * 35;
      const z1 = z0 + (rng() - 0.5) * 4;
      depMoves.push({
        line: i + 1, kind: 'G1',
        x0, y0, z0, x1, y1, z1,
        extruding: true, dE: 1, width: 0.45, height: 0.2, object: 'ObjA',
      });
    }

    storeCoarse.paint(depMoves);
    storeFineGrid.paint(depMoves);
    storeSmallMargin.paint(depMoves);
    refCoarse.paint(depMoves);

    const testMoves = [];
    for (let i = 0; i < 10; i++) {
      const x0 = 50 + rng() * 120;
      const y0 = 50 + rng() * 100;
      const x1 = 50 + rng() * 120;
      const y1 = 50 + rng() * 100;
      const z0 = 2 + rng() * 40;
      const z1 = 2 + rng() * 40;
      testMoves.push({
        line: i + 100, kind: 'G0',
        x0, y0, z0, x1, y1, z1,
        extruding: false, dE: 0, width: 0.45, height: 0.2, object: 'ObjB',
      });
    }

    const hitsCoarse = checkMoves(profile, storeCoarse, testMoves);
    const hitsRef = checkMovesReference(profile, refCoarse, testMoves);
    const hitsFineGrid = checkMoves(profile, storeFineGrid, testMoves);
    const hitsSmallMargin = checkMoves(profile, storeSmallMargin, testMoves);

    // Fast checker and reference checker must flag the exact same (line, part) pairs and penetrations
    assert.equal(hitsCoarse.length, hitsRef.length);
    for (let i = 0; i < hitsCoarse.length; i++) {
      assert.equal(hitsCoarse[i].line, hitsRef[i].line);
      assert.equal(hitsCoarse[i].part, hitsRef[i].part);
      assert.ok(Math.abs(hitsCoarse[i].penetration_mm - hitsRef[i].penetration_mm) <= 1e-3);
    }

    const coarseKeys = new Set(hitsCoarse.map(h => `${h.line}:${h.part}`));
    for (const hf of hitsFineGrid) {
      assert.ok(
        coarseKeys.has(`${hf.line}:${hf.part}`),
        `Halving grid added a new collision ${hf.line}:${hf.part} not present at coarse grid`
      );
    }
    for (const hm of hitsSmallMargin) {
      assert.ok(
        coarseKeys.has(`${hm.line}:${hm.part}`),
        `Shrinking margin added a new collision ${hm.line}:${hm.part} not present at larger margin`
      );
    }
  }
});

test('Phase 1 Property 4: Collapsed events cover the exact lines the reference checker flags and merge per-part streams', () => {
  // Place TallB at X=85 (25mm gap from TallA at X=50..60) so BOTH extruder (r=45) and gantry hit on the same moves!
  const gcode = buildBoxPlateGcode([
    { name: 'TallA', x0: 50, y0: 95, x1: 60, y1: 105, height: 50 },
    { name: 'TallB', x0: 85, y0: 95, x1: 95, y1: 105, height: 50 },
  ], { sequential: true });

  const fast = checkToolpath(gcode, 'mk4', { isText: true });
  const ref = checkToolpathReference(gcode, 'mk4', { isText: true });

  // Both extruder and gantry hit across dozens of moves, but collapseEvents merges each part into 1 incident (2 total)
  assert.equal(fast.events.length, 2);
  assert.deepEqual(fast.events.map(e => e.part).sort(), ['extruder', 'gantry']);

  const refLines = new Set(ref.rawEvents.map(e => e.line));
  const collapsedLines = new Set(fast.events.flatMap(e => e.lines));
  assert.deepEqual(collapsedLines, refLines);

  for (const ev of fast.events) {
    assert.ok(ev.first_line <= ev.last_line);
    assert.ok(refLines.has(ev.first_line));
    assert.ok(refLines.has(ev.last_line));
  }
});

