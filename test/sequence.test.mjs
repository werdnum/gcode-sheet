// Deterministic PRNG for property tests
function makeRng(seed = 0xCAFEBABE) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Generate a random valid topological ordering of chunks (respecting same-object Z-band precedence).
 */
function randomTopologicalChunkOrder(chunks, rng) {
  const n = chunks.length;
  const remaining = new Set(Array.from({ length: n }, (_, i) => i));
  const order = [];
  while (remaining.size > 0) {
    const eligible = [...remaining].filter(j => {
      for (const i of remaining) {
        if (chunks[i].object === chunks[j].object && chunks[i].bandIndex < chunks[j].bandIndex) {
          return false;
        }
      }
      return true;
    });
    const pick = eligible[Math.floor(rng() * eligible.length)];
    order.push(pick);
    remaining.delete(pick);
  }
  return order;
}

test('Phase 2 Emitter Properties 1, 3, 4, 5: Random chunk orders preserve extrusion, move counts, positions, state, and oracle agreement', () => {
  const gcode = buildInterleavedPlate([
    { name: 'BoxA', x0: 40, y0: 40, x1: 50, y1: 50, height: 28, accel: 'P1000', flow: 98 },
    { name: 'BoxB', x0: 140, y0: 40, x1: 150, y1: 50, height: 28, accel: 'P1500', flow: 100 },
    { name: 'BoxC', x0: 90, y0: 140, x1: 100, y1: 150, height: 16, accel: 'P1200', flow: 102 },
  ], { layerHeight: 4.0 });

  const profile = loadProfile('mk4');
  const inPath = loadToolpath(gcode, { profile });
  const extracted = extractChunks(inPath, { profile, colours: 'red,blue,red', splitAt: [16] });
  const matrixInfo = buildPairwiseMatrix(extracted);
  const rng = makeRng(4242);

  // Collect input extruding moves per object in Z order
  const inputMovesByObj = new Map();
  for (const obj of inPath.objects) {
    inputMovesByObj.set(obj.name, inPath.moves.filter(m => !m.inStart && m.extruding && m.object === obj.name));
  }
  const inputTotalE = inPath.objects.reduce((s, o) => s + o.extrusionLength, 0);

  for (let trial = 0; trial < 15; trial++) {
    const order = randomTopologicalChunkOrder(extracted.chunks, rng);
    const outGcode = emitResequencedGcode(extracted, order);
    const outPath = loadToolpath(outGcode, { profile });

    // Property 1: Total extrusion and per-object move counts equal the input
    const outTotalE = outPath.objects.reduce((s, o) => s + o.extrusionLength, 0);
    assert.ok(Math.abs(outTotalE - inputTotalE) < 1e-3, `Total extrusion mismatch: ${outTotalE} vs ${inputTotalE}`);
    assert.equal(outPath.objects.length, inPath.objects.length);
    for (const inObj of inPath.objects) {
      const outObj = outPath.objects.find(o => o.name === inObj.name);
      assert.ok(outObj, `Missing object ${inObj.name} in output`);
      assert.equal(outObj.moveCount, inObj.moveCount, `Move count mismatch for ${inObj.name}`);
      assert.ok(Math.abs(outObj.extrusionLength - inObj.extrusionLength) < 1e-3);
      assert.deepEqual(outObj.bbox, inObj.bbox);
    }

    // Property 3 & 4: Walker parses output to exact same absolute XYZ positions, extrusion deltas,
    // and non-motion printer state (fan, hotendTemp, bedTemp, accel, flow, width, height, type)
    for (const [objName, inMoves] of inputMovesByObj.entries()) {
      const outMoves = outPath.moves.filter(m => !m.inStart && m.extruding && m.object === objName);
      assert.equal(outMoves.length, inMoves.length);
      for (let i = 0; i < inMoves.length; i++) {
        const im = inMoves[i];
        const om = outMoves[i];
        assert.ok(Math.abs(om.x0 - im.x0) < 1e-3 && Math.abs(om.y0 - im.y0) < 1e-3 && Math.abs(om.z0 - im.z0) < 1e-3);
        assert.ok(Math.abs(om.x1 - im.x1) < 1e-3 && Math.abs(om.y1 - im.y1) < 1e-3 && Math.abs(om.z1 - im.z1) < 1e-3);
        assert.ok(Math.abs(om.dE - im.dE) < 1e-4);
        assert.ok(Math.abs(om.width - im.width) < 1e-4);
        assert.ok(Math.abs(om.height - im.height) < 1e-4);
        assert.equal(om.type, im.type);
        assert.equal(om.state.fan, im.state.fan);
        assert.equal(om.state.hotendTemp, im.state.hotendTemp);
        assert.equal(om.state.bedTemp, im.state.bedTemp);
        assert.equal(om.state.accel, im.state.accel);
        assert.equal(om.state.flow, im.state.flow);
      }
    }

    // Property 5: Phase 1 checker verdict on output matches sequencer's pairwise prediction
    const predictedFeasible = isOrderPairwiseFeasible(extracted.chunks, matrixInfo.ok, order);
    const checkRes = checkToolpath(outPath, profile);
    assert.equal(
      !checkRes.collides,
      predictedFeasible,
      `Trial ${trial} order [${order.join(',')}]: checker collides=${checkRes.collides} vs predictedFeasible=${predictedFeasible}`
    );
  }
});

