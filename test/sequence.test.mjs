test('File order is a candidate: a plate nothing can improve passes through unchanged (exit 0)', () => {
  // Two objects, each two colours side by side within nozzle reach on every layer, sliced like
  // PrusaSlicer (each layer starts with the current tool): one change per layer is already the
  // minimum, so any plan only matches or adds changes and the file is returned as is.
  const obj = (name, x) => ({ name, parts: [
    { x0: x, y0: 80, x1: x + 10, y1: 100, z0: 0, z1: 4, tool: 0 },
    { x0: x + 11, y0: 80, x1: x + 21, y1: 100, z0: 0, z1: 4, tool: 1 },
  ] });
  const gcode = buildPartsPlate([obj('P', 40), obj('Q', 150)], { layerHeight: 0.4, currentToolFirst: true });
  const res = sequenceToolpath(gcode, { internals: true });
  assertPlanInvariants(gcode, res, 'file order wins');
  assert.equal(res.pass_through, true);
  assert.equal(res.planner.name, 'file-order');
  assert.match(res.planner.reason, /needs \d+ filament change\(s\), the file's own order \d+/);
  assert.equal(res.gcode, gcode);
  assert.ok(res.planner.considered.filament_changes >= res.comparison.original_file.filament_changes);
  assert.ok('travel_distance_mm' in res);
  assert.ok(res.planner.considered.clusters.length > 0);
  assert.deepEqual(res.warnings.filter(w => /not regenerated|not emitted/.test(w)), []);

  const inPath = path.join(dir, `fileorder-${serial++}.gcode`);
  const outPath = path.join(dir, `fileorder-out-${serial++}.gcode`);
  fs.writeFileSync(inPath, gcode);
  const cli = runSequenceCli([inPath, '-o', outPath]);
  assert.equal(cli.status, 0, cli.stderr);
  assert.match(cli.stdout, /No improvement: keeping the file's own order/);
  assert.equal(fs.readFileSync(outPath, 'utf8'), gcode);
});

test('MMU files: the first chunk gets its tool select, changes are T<n>, and the tool-change cost comes from the file', () => {
  // The start block leaves T2 selected, which no object uses; A (T1, short) must print before
  // B (T0, tall, in the gantry band), so the plan is A then B: T2->T1 is a real change too.
  const objs = [
    { name: 'A', parts: [{ x0: 50, y0: 95, x1: 60, y1: 105, z0: 0, z1: 12, tool: 1 }] },
    { name: 'B', parts: [{ x0: 150, y0: 95, x1: 160, y1: 105, z0: 0, z1: 36, tool: 0 }] },
  ];
  const footer = ['; filament_load_time = 10.5,10.5,10.5', '; filament_unload_time = 8.5,8.5,8.5'];
  const gcode = buildPartsPlate(objs, { layerHeight: 2, toolCmd: 'T', preamble: ['T2'], footer });
  const res = sequenceToolpath(gcode, { internals: true });
  assertPlanInvariants(gcode, res, 'mmu');
  assert.equal(res.internals.extracted.colourChangeBy, 'T');
  assert.equal(res.internals.extracted.initialColour, 'T2');
  const body = res.gcode.slice(res.gcode.indexOf('; --- gcode-sequence normalised state ---'));
  const selects = body.match(/^(T\d|M600)$/gm);
  assert.equal(selects.length, res.filament_changes);
  assert.equal(selects[0], 'T1', 'the first chunk selects its tool');
  // Every extruding move of A runs on T1, every move of B on T0.
  const out = loadToolpath(res.gcode);
  for (const m of out.moves.filter(mv => mv.extruding && !mv.inStart && mv.object)) {
    assert.equal(m.tool, m.object === 'A' ? 1 : 0, `${m.object} printed with T${m.tool}`);
  }
  assert.deepEqual(res.change_cost, { change_cost_s: 19, source: 'filament_unload_time + filament_load_time from the file' });
  assert.ok(res.warnings.some(w => /purging is not regenerated/.test(w)));

  const noFooter = sequenceToolpath(buildPartsPlate(objs, { layerHeight: 2, toolCmd: 'T', preamble: ['T2'] }));
  assert.equal(noFooter.change_cost.change_cost_s, 30);

  // M600 mode: the start block selects T0 (B's filament) but the plan starts with A (T1), so the
  // first chunk gets an M600 too, and it is counted.
  const m600 = buildPartsPlate(objs, { layerHeight: 2, preamble: ['T0'] });
  const m600Res = sequenceToolpath(m600, { internals: true });
  assertPlanInvariants(m600, m600Res, 'm600 first chunk');
  assert.equal(m600Res.internals.extracted.colourChangeBy, 'M600');
  assert.deepEqual(m600Res.steps.map(s => s.object)[0], 'A');
  assert.equal(m600Res.filament_changes, 2);
  const m600Body = m600Res.gcode.slice(m600Res.gcode.indexOf('; --- gcode-sequence normalised state ---'));
  assert.ok(m600Body.indexOf('M600') < m600Body.indexOf('; printing object A'), 'M600 before the first chunk');
  assert.equal(m600Res.change_cost.source, 'profile change_cost_s, M600');

  // A T0 in a markerless preamble with one tool in use is not an MMU file.
  const markerless = ['T0', 'G90', 'M83', '; printing object A', 'G0 X10 Y10 Z0.2', 'G1 X20 Y10 Z0.2 E1 F1800', '; stop printing object A'].join('\n');
  assert.equal(extractSlices(loadToolpath(markerless), {}).colourChangeBy, 'M600');
});

test('Pass-through details: zero-change files are only checked, text vs path inputs, byte copy, report fields', () => {
  // Zero colour changes: no planning at all.
  const one = sequenceToolpath(fixture('seq-short-sbs.gcode'));
  assert.equal(one.pass_through, true);
  assert.match(one.planner.reason, /no colour changes/);
  assert.equal(one.planner.considered, undefined);

  // The --planner fixed path keeps the file order too.
  const fixedKeep = sequenceToolpath(fixture('seq-short-sbs.gcode'), { colours: 'red,blue', planner: 'fixed' });
  assert.equal(fixedKeep.pass_through, true);
  assert.equal(fixedKeep.planner.considered.planner.name, 'fixed');

  // Text in, text out; isText is honoured; a path is returned as a path, never read back.
  const obj = (name, x) => ({ name, parts: [
    { x0: x, y0: 80, x1: x + 10, y1: 100, z0: 0, z1: 4, tool: 0 },
    { x0: x + 11, y0: 80, x1: x + 21, y1: 100, z0: 0, z1: 4, tool: 1 },
  ] });
  const text = buildPartsPlate([obj('P', 40), obj('Q', 150)], { layerHeight: 0.4, currentToolFirst: true })
    .replace('; generated by PrusaSlicer 2.9.6', '; generated by PrusaSlicer 2.9.6 café');
  assert.equal(sequenceToolpath(text, { isText: true }).gcode, text);
  const latin1 = Buffer.from(text, 'latin1');
  const inPath = path.join(dir, `latin1-${serial++}.gcode`);
  const outPath = path.join(dir, `latin1-out-${serial++}.gcode`);
  const jsonPath = path.join(dir, `latin1-${serial++}.json`);
  fs.writeFileSync(inPath, latin1);
  const viaPath = sequenceToolpath(inPath);
  assert.deepEqual([viaPath.pass_through, viaPath.gcode, viaPath.source_path], [true, null, inPath]);

  // CLI: a byte copy (a Latin-1 byte survives), and the report describes the kept file.
  const cli = runSequenceCli([inPath, '-o', outPath, '--json', jsonPath]);
  assert.equal(cli.status, 0, cli.stderr);
  assert.ok(fs.readFileSync(outPath).equals(latin1));
  const report = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  for (const key of ['feasible', 'verified', 'printer', 'warnings', 'order', 'filament_changes', 'travel_distance_mm', 'estimated_time_s', 'change_cost', 'steps', 'clusters', 'planner', 'comparison', 'output']) {
    assert.ok(key in report, `report lacks ${key}`);
  }
  assert.deepEqual(report.clusters, []);
  assert.ok(report.planner.considered.clusters.length > 0);
  assert.equal(report.filament_changes, report.comparison.original_file.filament_changes);
});
