/**
 * Plan invariants that hold for every accepted plan:
 * - the emitted file verifies clean with the phase-1 checker;
 * - each object's steps are contiguous and in Z order (0 -> top) and together cover every
 *   layer slice of the object exactly once, and no step crosses a colour boundary;
 * - the emitted file preserves per-object extrusion totals, extruding move counts and bboxes.
 */
/**
 * Independent support check (not the planner's footprints): every emitted slice whose
 * extrusion bounding box overlaps, by more than a line width, the bounding box of another
 * colour region of the same object on that object's layer just below, must come after it.
 * For the rectangular parts the tests synthesise, bounding boxes are the footprints.
 */
function sliceBox(sl) {
  const b = [Infinity, Infinity, -Infinity, -Infinity];
  for (const c of sl.commands) {
    if ((c.kind !== 'move' && c.kind !== 'arc') || !c.extruding) continue;
    b[0] = Math.min(b[0], c.x0, c.x1); b[1] = Math.min(b[1], c.y0, c.y1);
    b[2] = Math.max(b[2], c.x0, c.x1); b[3] = Math.max(b[3], c.y0, c.y1);
  }
  return b;
}
function assertSupported(chunks, label) {
  const order = chunks.flatMap(st => st.slices);
  const pos = new Map(order.map((sl, i) => [sl, i]));
  const byObject = new Map();
  for (const sl of order) {
    if (!byObject.has(sl.object)) byObject.set(sl.object, []);
    byObject.get(sl.object).push(sl);
  }
  for (const slices of byObject.values()) {
    const zs = [...new Set(slices.map(sl => sl.z))].sort((a, b) => a - b);
    for (const sl of slices) {
      const t = zs.indexOf(sl.z);
      if (t <= 0) continue;
      const box = sliceBox(sl);
      for (const below of slices) {
        if (below.z !== zs[t - 1] || below.colour === sl.colour) continue;
        const bb = sliceBox(below);
        const ox = Math.min(box[2], bb[2]) - Math.max(box[0], bb[0]);
        const oy = Math.min(box[3], bb[3]) - Math.max(box[1], bb[1]);
        if (ox > 0.5 && oy > 0.5) {
          assert.ok(pos.get(below) < pos.get(sl), `${label}: ${sl.object} (${sl.colour}) Z${sl.z} printed before its support (${below.colour}) Z${below.z}`);
        }
      }
    }
  }
}

function assertPlanInvariants(input, res, label, printer = 'mk4') {
  assert.equal(res.feasible, true, `${label}: infeasible`);
  assert.equal(res.verified, true, `${label}: not verified`);
  if (res.pass_through) {
    // No plan beat the file's own order: the input is returned unchanged.
    assert.equal(res.planner.name, 'file-order', label);
    if (input.includes('\n')) assert.equal(res.gcode, input, `${label}: pass-through changed the text`);
    else assert.deepEqual([res.gcode, res.source_path], [null, input], `${label}: a file passes through by path`);
    assert.equal(res.filament_changes, res.comparison.original_file.filament_changes);
    assert.deepEqual(res.clusters, []);
    const c = res.planner.considered;
    if (c && c.filament_changes !== undefined) assert.ok(c.filament_changes >= res.filament_changes);
    return;
  }
  assert.ok(res.filament_changes < res.comparison.original_file.filament_changes || res.warnings.some(w => /own order collides/.test(w)),
    `${label}: plan does not beat the file order`);
  assert.equal(checkToolpath(res.gcode, printer).collides, false, `${label}: emitted file collides`);

  const { extracted, chunks } = res.internals;
  const unitTop = new Map();
  for (const st of chunks) {
    assert.ok(st.zHi > st.zLo, `${label}: ${st.object} step not upward`);
    // Bands of one unit are contiguous: each starts where the previous one stopped.
    if (unitTop.has(st.object)) assert.equal(st.zLo, unitTop.get(st.object), `${label}: ${st.object} band gap`);
    unitTop.set(st.object, st.zHi);
    let changes = 0;
    for (let i = 1; i < st.slices.length; i++) if (st.slices[i].colour !== st.slices[i - 1].colour) changes++;
    assert.equal(changes, st.internalChanges, `${label}: internal colour changes`);
    if (!st.members || st.members.length === 1) assert.equal(changes, 0, `${label}: single-unit step crosses a colour boundary`);
  }
  // Every object's layer slices are emitted exactly once, and each colour region of an object
  // (all of it, for a one-colour object) in Z order.
  for (const [name, slices] of extracted.objectLayerSlices) {
    if (slices.length === 0) continue;
    const emitted = chunks.flatMap(st => st.slices.filter(sl => sl.object === name));
    assert.equal(emitted.length, slices.length, `${label}: ${name} layer count`);
    assert.equal(new Set(emitted).size, slices.length, `${label}: ${name} slice repeated`);
    for (const sl of slices) assert.ok(emitted.includes(sl), `${label}: ${name} slice missing`);
    for (const colour of new Set(slices.map(sl => sl.colour))) {
      const zs = emitted.filter(sl => sl.colour === colour).map(sl => sl.z);
      for (let i = 1; i < zs.length; i++) assert.ok(zs[i] >= zs[i - 1], `${label}: ${name} (${colour}) out of Z order`);
    }
  }
  assertSupported(chunks, label);
  // Changes counted from what the start block left loaded (nothing known: the first is free).
  const loaded = extracted.initialColour;
  const expectedChanges = chunks.reduce((n, st, i) =>
    n + st.internalChanges + ((i > 0 ? chunks[i - 1].lastColour : loaded) !== st.colour && (i > 0 || loaded !== null) ? 1 : 0), 0);
  assert.equal(res.filament_changes, expectedChanges, `${label}: change count`);
  // Count the emitter's own changes (start G-code may carry the slicer's initial tool change).
  const body = res.gcode.slice(res.gcode.indexOf('; --- gcode-sequence normalised state ---'));
  const changeLine = extracted.colourChangeBy === 'T' ? /^T\d+$/gm : /^M600$/gm;
  assert.equal((body.match(changeLine) || []).length, expectedChanges, `${label}: colour change commands`);

  const inPath = loadToolpath(input);
  const outPath = loadToolpath(res.gcode);
  for (const inObj of inPath.objects) {
    const outObj = outPath.objects.find(o => o.name === inObj.name);
    assert.ok(outObj, `${label}: missing ${inObj.name}`);
    assert.equal(outObj.moveCount, inObj.moveCount, `${label}: ${inObj.name} move count`);
    assert.ok(Math.abs(outObj.extrusionLength - inObj.extrusionLength) < 1e-3, `${label}: ${inObj.name} extrusion`);
    assert.deepEqual(outObj.bbox, inObj.bbox);
    // Within a one-colour object the emitted layers only ever go up.
    if (new Set(extracted.objectLayerSlices.get(inObj.name).map(sl => sl.colour)).size === 1) {
      const zs = outPath.moves.filter(m => m.extruding && !m.inStart && m.object === inObj.name).map(m => m.z0);
      for (let i = 1; i < zs.length; i++) assert.ok(zs[i] >= zs[i - 1] - 1e-6, `${label}: ${inObj.name} Z goes down`);
    }
  }
}

