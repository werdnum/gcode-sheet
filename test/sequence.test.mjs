const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gcode-sequence-test-'));
after(() => fs.rmSync(dir, { recursive: true, force: true }));
let serial = 0;

function runSequenceCli(args) {
  const cli = process.env.GCODE_SEQUENCE_BIN;
  const command = cli || process.execPath;
  const prefix = cli ? [] : [fileURLToPath(new URL('../gcode-sequence.mjs', import.meta.url))];
  return spawnSync(command, [...prefix, ...args], { encoding: 'utf8', timeout: 30000 });
}

function renderTopView(gcode) {
  const base = path.join(dir, `render-${serial++}`);
  fs.writeFileSync(base + '.gcode', gcode);
  const cli = process.env.GCODE_SHEET_BIN;
  const command = cli || process.execPath;
  const prefix = cli ? [] : [fileURLToPath(new URL('../gcode-sheet.mjs', import.meta.url))];
  const summary = JSON.parse(execFileSync(command, [
    ...prefix, base + '.gcode', base + '.png',
    '--size', '160', '--views', 'top', '--no-labels', '--detail', 'full',
  ], { encoding: 'utf8', timeout: 30000 }));
  const png = fs.readFileSync(base + '.png');
  delete summary.output;
  return { summary, png };
}

/**
 * Extract a standalone G-code snippet containing only the extruding moves of a single object
 * from a parsed toolpath so we can render that object alone in gcode-sheet's top view.
 */
function isolateObjectGcode(toolpath, objectName) {
  const lines = ['G21', 'G90', 'M83'];
  let prevZ = null;
  for (const cmd of toolpath.commands) {
    if (cmd.inStart || cmd.object !== objectName) continue;
    if ((cmd.kind === 'move' || cmd.kind === 'arc') && cmd.extruding) {
      if (cmd.z0 !== prevZ) {
        lines.push(';LAYER_CHANGE');
        lines.push(`;Z:${cmd.z0.toFixed(3)}`);
        prevZ = cmd.z0;
      }
      lines.push(`;HEIGHT:${(cmd.height || 0.2).toFixed(3)}`);
      lines.push(`;WIDTH:${(cmd.width || 0.45).toFixed(3)}`);
      lines.push(`;TYPE:${cmd.type || 'External perimeter'}`);
      lines.push(`G0 X${cmd.x0.toFixed(4)} Y${cmd.y0.toFixed(4)} Z${cmd.z0.toFixed(4)} F7800`);
      if (cmd.kind === 'move') {
        lines.push(`G1 X${cmd.x1.toFixed(4)} Y${cmd.y1.toFixed(4)} Z${cmd.z1.toFixed(4)} E${cmd.dE.toFixed(5)} F1800`);
      } else {
        const iPart = cmd.i === cmd.i ? ` I${cmd.i.toFixed(4)}` : '';
        const jPart = cmd.j === cmd.j ? ` J${cmd.j.toFixed(4)}` : '';
        const rPart = cmd.r === cmd.r ? ` R${cmd.r.toFixed(4)}` : '';
        lines.push(`${cmd.cmd} X${cmd.x1.toFixed(4)} Y${cmd.y1.toFixed(4)} Z${cmd.z1.toFixed(4)}${iPart}${jPart}${rPart} E${cmd.dE.toFixed(5)} F1800`);
      }
    }
  }
  return lines.join('\n') + '\n';
}

/**
 * Build an interleaved (layer-by-layer) multi-object G-code plate with rich printer state.
 */
function buildInterleavedPlate(boxes, { layerHeight = 2.0, width = 0.45 } = {}) {
  const lines = [
    '; generated by PrusaSlicer 2.9.6',
    'G21',
    'G90',
    'M83',
    'M104 S215',
    'M140 S60',
    'M107',
    'G28',
    'G1 X10 Y-3 Z0.2 E5.0 F1000 ; intro line',
  ];

  const maxHeight = Math.max(...boxes.map(b => b.height));
  const totalLayers = Math.max(1, Math.round(maxHeight / layerHeight));

  for (let l = 1; l <= totalLayers; l++) {
    const z = +(l * layerHeight).toFixed(3);
    lines.push(';LAYER_CHANGE');
    lines.push(`;Z:${z.toFixed(3)}`);
    lines.push(`;HEIGHT:${layerHeight.toFixed(3)}`);
    if (l === 1) {
      lines.push('M107');
      lines.push('M104 S220');
      lines.push('M140 S60');
    } else if (l === 2) {
      lines.push('M106 S128');
      lines.push('M104 S215');
    } else {
      lines.push('M106 S255');
    }

    for (let bIdx = 0; bIdx < boxes.length; bIdx++) {
      const box = boxes[bIdx];
      if (z > box.height + 1e-6) continue;
      const { name, x0, y0, x1, y1, accel = 'P1200', flow = 100 } = box;
      lines.push(`; printing object ${name}`);
      lines.push(`M204 ${accel}`);
      lines.push(`M221 S${flow}`);
      lines.push(`;WIDTH:${width.toFixed(3)}`);
      lines.push(`;TYPE:External perimeter`);
      lines.push(`G1 E-0.8 F2400`);
      lines.push(`G0 X${x0.toFixed(3)} Y${y0.toFixed(3)} Z${z.toFixed(3)} F7800`);
      lines.push(`G1 E0.8 F2400`);
      lines.push(`G1 X${x1.toFixed(3)} Y${y0.toFixed(3)} E1.25 F1800`);
      lines.push(`G1 X${x1.toFixed(3)} Y${y1.toFixed(3)} E1.25 F1800`);
      lines.push(`G1 X${x0.toFixed(3)} Y${y1.toFixed(3)} E1.25 F1800`);
      lines.push(`G1 X${x0.toFixed(3)} Y${y0.toFixed(3)} E1.25 F1800`);
      lines.push(`; stop printing object ${name}`);
    }
  }

  lines.push('M107');
  lines.push('M104 S0');
  lines.push('M140 S0');
  lines.push('G0 X0 Y210 F7800 ; park');
  lines.push('M84');
  return lines.join('\n') + '\n';
}

test('Phase 2 fixtures: short cubes grouped by colour + tall cube printed last minimizes filament changes', () => {
  // 3 objects: ShortRed (12mm), ShortBlue (12mm), TallRed (50mm).
  // Optimal collision-free order prints ShortBlue (blue) -> ShortRed (red) -> TallRed (red):
  // - Only 1 filament change (blue -> red)
  // - TallRed is printed last so the gantry never has to drop back to Z=2.0 next to a 50mm tower.
  const gcode = buildInterleavedPlate([
    { name: 'ShortRed', x0: 40, y0: 95, x1: 50, y1: 105, height: 12 },
    { name: 'ShortBlue', x0: 110, y0: 95, x1: 120, y1: 105, height: 12 },
    { name: 'TallRed', x0: 180, y0: 95, x1: 190, y1: 105, height: 50 },
  ]);

  const res = sequenceToolpath(gcode, { colours: 'ShortRed=red,ShortBlue=blue,TallRed=red' });
  assert.equal(res.feasible, true);
  assert.equal(res.verified, true);
  assert.equal(res.filament_changes, 1);
  assert.deepEqual(res.order, ['ShortBlue', 'ShortRed', 'TallRed']);
  assert.equal(checkToolpath(res.gcode, 'mk4').collides, false);
});

